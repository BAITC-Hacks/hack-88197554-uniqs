export type KnowledgeArticle = (typeof ARTICLES)[number];

export function findArticles(query: string, limit = 3): KnowledgeArticle[] {
  const text = query.toLocaleLowerCase("ru").replaceAll("ё", "е");
  return ARTICLES.map(article => ({
    article,
    score: article.keywords.reduce((score, word) => score + (text.includes(word.replaceAll("ё", "е")) ? 1 : 0), 0),
  })).filter(item => item.score > 0).sort((a, b) => b.score - a.score)
    .slice(0, limit).map(item => item.article);
}
